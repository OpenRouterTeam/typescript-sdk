#!/usr/bin/env node
/**
 * Rebuild the public model barrels after Speakeasy generation.
 *
 * `useIndexModules: false` in `.speakeasy/gen.yaml` stops Speakeasy from
 * writing `index.ts` barrels, so generated code imports each model by file
 * path and bundlers can drop the models a consumer never reaches. The
 * package still exports `./models`, `./models/operations` and
 * `./models/errors`, so this script writes those barrels back. Nothing
 * inside `src/` imports them; `tests/unit/model-barrels.test.ts` enforces
 * that and keeps the barrels in sync.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SRC = join(resolve(dirname(fileURLToPath(import.meta.url)), '..'), 'src');
export const BARREL_DIRS = ['models', 'models/operations', 'models/errors'];

const GENERATED_MARKER = 'Code generated by Speakeasy';
const HEADER = [
  '/*',
  ' * Generated by scripts/barrels.mjs. DO NOT EDIT.',
  ' * Public entry point only: code inside src/ must import models by file path.',
  ' */',
  '',
].join('\n');

const isModule = (name) => name.endsWith('.ts') && !name.endsWith('.d.ts') && name !== 'index.ts';

/** Barrel source for one directory: every Speakeasy-generated module in it. */
export function renderBarrel(dir) {
  const names = readdirSync(join(SRC, dir), { withFileTypes: true })
    .filter((entry) => entry.isFile() && isModule(entry.name))
    .filter((entry) => readFileSync(join(SRC, dir, entry.name), 'utf8').includes(GENERATED_MARKER))
    .map((entry) => entry.name.replace(/\.ts$/, ''))
    .sort();
  return `${HEADER}\n${names.map((name) => `export * from "./${name}.js";`).join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const dir of BARREL_DIRS) {
    writeFileSync(join(SRC, dir, 'index.ts'), renderBarrel(dir));
  }
}
